# Draws the masthead of the prep's newspaper view, «Kvisspoſten», as SVG outlines and writes
# data/paper-logo.js. Run from the repo root:
#
#   python3 tools/make-paper-logo.py UnifrakturMaguntia.ttf
#
# The font is the original UnifrakturMaguntia (SIL Open Font License): UnifrakturMaguntia.ttf at the
# top of UnifrakturMaguntia.2017-03-19.zip, from https://unifraktur.sourceforge.net/maguntia.html —
# not the ones in switched-on_features/, which swap s and ſ. The one on Google Fonts has no long s,
# so the browser drew it in another font; hence outlines. The ligatures and contextual forms are
# turned off, so the first two s-es stay round and only the last one is long.
# Needs fonttools and uharfbuzz (pip install fonttools uharfbuzz).
import sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

TEXT = 'Kvisspoſten'
OFF = {t: False for t in ('liga', 'calt', 'clig', 'dlig', 'rlig', 'hlig')}

path = sys.argv[1]
font = TTFont(path)
glyphs = font.getGlyphSet()
hbfont = hb.Font(hb.Face(hb.Blob.from_file_path(path)))
buf = hb.Buffer(); buf.add_str(TEXT); buf.guess_segment_properties()
hb.shape(hbfont, buf, OFF)

svg = SVGPathPen(glyphs, ntos=lambda v: str(round(v)))
bounds = BoundsPen(glyphs)
x = 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    name = hbfont.glyph_to_string(info.codepoint)
    for pen in (svg, bounds):   # y flipped: font units go up, SVG goes down
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
    x += pos.x_advance

x0, y0, x1, y1 = (round(v) for v in bounds.bounds)   # already flipped: y0 is the top
pad = 8
box = f'{x0 - pad} {y0 - pad} {x1 - x0 + 2 * pad} {y1 - y0 + 2 * pad}'
out = ("// Generated by tools/make-paper-logo.py; don't edit by hand. The masthead of the prep's newspaper\n"
       "// view, «Kvisspoſten» in UnifrakturMaguntia (SIL Open Font License), as outlines in currentColor.\n"
       f"const PAPER_LOGO='<svg viewBox=\"{box}\" xmlns=\"http://www.w3.org/2000/svg\" role=\"img\" aria-label=\"Kvissposten\">"
       f"<path fill=\"currentColor\" d=\"{svg.getCommands()}\"/></svg>';\n")
open('data/paper-logo.js', 'w').write(out)
print('data/paper-logo.js', len(out), 'bytes')
